$ErrorActionPreference = "Stop"
$queryScripts = Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) "agentloop-audit-query\scripts"
. (Join-Path $queryScripts "lib\config-record.ps1")
. (Join-Path $queryScripts "lib\aliyun.ps1")

function Test-ConfValue([string]$Flag, [string]$Value) {
    if ($Value -match '[\x00-\x1f\x7f\\"$`]') {
        Fail ("Install argument " + $Flag + " contains a character that cannot be written safely")
    }
}

function Write-InstallConf([string]$Path, $Fields, [string]$UserIdSource) {
    $lines = @(
        "# Generated by agentloop.",
        "# Account values stay on this machine.",
        "",
        "INSTALL_ARGS=("
    )
    foreach ($pair in $Fields) {
        Test-ConfValue $pair[0] $pair[1]
        $lines += "    " + $pair[0] + ' "' + $pair[1] + '"'
    }
    $lines += ")"
    $lines += ""
    if ($UserIdSource) {
        $lines += "USER_ID_SOURCE=$UserIdSource"
        $lines += ""
    }
    Write-Utf8NoBom $Path ($lines -join "`n")
}

function Report-Installed {
    if (-not (Test-Interactive)) {
        if (Test-Path -LiteralPath $script:ENTERPRISE_ZIP) { Write-Output "enterprise installed" }
        return
    }
    if (Test-Path -LiteralPath $script:ENTERPRISE_ZIP) { Write-Host "Zip: already created" }
}

function Get-InstallFields([string]$Profile, [string]$AgentSpace, [string]$Region) {
    $space = Get-AgentSpace $Profile $AgentSpace $Region
    if ([string]$space.agentSpace) { $AgentSpace = [string]$space.agentSpace }
    if ([string]$space.regionId) { $Region = [string]$space.regionId }
    $project = [string]$space.slsProject
    $workspace = [string]$space.cmsWorkspace
    if (-not $project -or -not $workspace) { Fail "AgentSpace is missing slsProject or cmsWorkspace" }
    $access = Get-Observability $Profile $Region $workspace
    $token = [string]$access.authToken
    $domain = [string]$access.publicDomain
    if (-not $domain) { $domain = [string]$access.privateDomain }
    if (-not $token -or -not $domain) { Fail "Service observability result is missing authToken or domain" }
    $trimmed = $domain.TrimEnd("/")
    if ($domain.Contains("://")) {
        $endpoint = $trimmed + "/apm/trace/opentelemetry"
    } else {
        $endpoint = "https://" + $trimmed + "/apm/trace/opentelemetry"
    }
    $key = Get-PilotApiKey $Profile $Region $project
    $fields = @(
        @("--collect-log", "true"),
        @("--collect-trace", "true"),
        @("--sls-project", $project),
        @("--sls-logstore", $script:DEFAULT_LOGSTORE),
        @("--sls-endpoint", ($Region + ".log.aliyuncs.com")),
        @("--cms-license-key", $token),
        @("--cms-endpoint", $endpoint),
        @("--cms-workspace", $workspace),
        @("--service-name-prefix", "ai-coding-agent"),
        @("--sls-api-key", $key)
    )
    return @{ Fields = $fields; Project = $project; Region = $Region; AgentSpace = $AgentSpace }
}

function Find-PluginRoot([string]$Root) {
    $script:FoundPlugin = ""
    Get-ChildItem -LiteralPath $Root -Recurse -Directory -Filter $script:INSTALLER_NAME -ErrorAction SilentlyContinue | ForEach-Object {
        if ($script:FoundPlugin) { return }
        $manifest = Join-Path $_.FullName ".qoder-plugin\plugin.json"
        if (Test-Path -LiteralPath $manifest) { $script:FoundPlugin = $_.FullName }
    }
    $found = $script:FoundPlugin
    $script:FoundPlugin = ""
    if (-not $found) { Fail ("Package does not contain " + $script:INSTALLER_NAME) }
    return $found
}

function Get-PublishedPlugin([string]$Stage) {
    $archive = Join-Path $Stage "loongsuite-pilot-installer.zip"
    $url = $script:PLUGIN_ZIP_URL
    try {
        Invoke-DownloadFile $url $archive
    } catch {
        $detail = ([string]$_).Trim()
        if ($detail) { Fail ("Download failed: " + $url + " (" + $detail + ")") }
        Fail ("Download failed: " + $url)
    }
    $unpacked = Join-Path $Stage "unpacked"
    New-Item -ItemType Directory -Path $unpacked -Force | Out-Null
    if (-not (Expand-ZipArchive $archive $unpacked)) { Fail "Failed to unzip the Qoder plugin" }
    $pluginDir = Find-PluginRoot $unpacked
    return $pluginDir
}

function Install-Enterprise([string]$PluginDir) {
    $names = @(Get-ChildItem -Force -Name -LiteralPath $PluginDir)
    $tar = Get-TarExe
    if ($tar.NativeCount -eq 0) { Fail "Windows tar not found" }
    $zipLeaf = ".enterprise-" + $PID + "-" + (Get-Random) + ".zip"
    $zipTmp = Join-Path $PluginDir $zipLeaf
    $oldLocation = (Get-Location).Path
    $prev = $ErrorActionPreference
    $rc = 1
    try {
        Set-Location -LiteralPath (Get-AuditLongPath $PluginDir)
        $ErrorActionPreference = "Continue"
        $exe = $tar.Exes[0]
        $tarArgs = @("-a", "-cf", $zipLeaf) + $names
        & $exe @tarArgs 2>$null
        $rc = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prev
        try { Set-Location -LiteralPath (Get-AuditLongPath $oldLocation) } catch {}
    }
    if ($rc -ne 0) { Fail "Failed to pack the zip" }
    $destDir = Split-Path -Parent $script:ENTERPRISE_ZIP
    if (-not (Test-Path -LiteralPath $destDir)) { New-Item -ItemType Directory -Path $destDir -Force | Out-Null }
    Move-Item -LiteralPath (Get-AuditLongPath $zipTmp) -Destination $script:ENTERPRISE_ZIP -Force
    Write-Output ("enterprise_zip=" + $script:ENTERPRISE_ZIP)
}

$parsed = Get-CliMap $args @("agent-space", "region", "user-id-source") @()
$agentSpace = Get-CliValue $parsed "agent-space"
$region = Get-CliValue $parsed "region"
$userIdSource = Get-CliValue $parsed "user-id-source"
if ($userIdSource -and @("hostname", "username", "email") -notcontains $userIdSource) {
    Fail "Invalid user id source. It must be hostname, username, or email"
}
$profile = Require-Profile
if (-not $agentSpace) { Report-Installed }
$built = Get-InstallFields $profile $agentSpace $region
$built.Fields += ,@("--install-source", $script:INSTALL_SOURCE)
$downloadStage = Join-Path (Get-AsciiTempRoot) ("qoder-plugin-download-" + $PID + "-" + (Get-Random))
$privateStage = Join-Path $script:DATA_DIR (".plugin-stage-" + $PID + "-" + (Get-Random))
try {
    New-Item -ItemType Directory -Path $downloadStage -Force | Out-Null
    New-Item -ItemType Directory -Path $privateStage -Force | Out-Null
    $downloadedPlugin = Get-PublishedPlugin $downloadStage
    Move-Item -LiteralPath (Get-AuditLongPath $downloadedPlugin) -Destination $privateStage
    $pluginDir = Join-Path $privateStage $script:INSTALLER_NAME
    Write-InstallConf (Join-Path $pluginDir "config\install-params.conf") $built.Fields $userIdSource
    Install-Enterprise $pluginDir
} finally {
    Remove-AuditPathQuietly $downloadStage
    Remove-AuditPathQuietly $privateStage
}
Save-AuditTarget $built.AgentSpace $built.Region $built.Project $script:DEFAULT_LOGSTORE | Out-Null
