#!/usr/bin/env python3
"""安装。由 scripts/run.py 的 install 子命令调用。"""

import argparse
import os
import re
import shutil
import stat
import sys
import tempfile
import zipfile

from util.aliyun import (
    download_file,
    get_api_key,
    get_observability,
    get_space,
)
from util.config_record import (
    DATA_DIR,
    DEFAULT_LOGSTORE,
    atomic_private_file,
    fail,
    require_profile,
    save_target,
    write_private_text,
)

INSTALLER_NAME = "loongsuite-pilot-installer"
INSTALL_SOURCE = "qoder-marketplace"
ENTERPRISE_ZIP = os.path.join(DATA_DIR, "%s.zip" % INSTALLER_NAME)
PLUGIN_ZIP_URL = "https://aliyun-observability-release-cn-shanghai.oss-cn-shanghai.aliyuncs.com/loongsuite-pilot/loongsuite-pilot-installer.zip"


def parse_args(argv):
    parser = argparse.ArgumentParser(prog="install", add_help=False, allow_abbrev=False)
    parser.add_argument("--agent-space", dest="agent_space", default="")
    parser.add_argument("--region", default="")
    parser.add_argument("--user-id-source", dest="user_id_source", default="", choices=("hostname", "username", "email"))
    args = parser.parse_args(argv)
    return args.agent_space, args.region, args.user_id_source


# Bash sources this file; Windows copies the quotes literally. Reject unsafe characters.
_UNSAFE_CONF_VALUE = re.compile(r'[\x00-\x1f\x7f\\"$`]')


def quote_conf_value(flag, value):
    text = str(value)
    if _UNSAFE_CONF_VALUE.search(text):
        fail("Install argument %s contains a character that cannot be written safely" % flag)
    return '"' + text + '"'


def write_conf(path, fields, user_id_source=""):
    lines = [
        "# Generated by agentloop.",
        "# Account values stay on this machine.",
        "",
        "INSTALL_ARGS=(",
    ]
    for flag, value in fields:
        lines.append("    %s %s" % (flag, quote_conf_value(flag, value)))
    lines.append(")")
    lines.append("")
    if user_id_source:
        lines.append("USER_ID_SOURCE=%s" % user_id_source)
        lines.append("")
    write_private_text(path, "\n".join(lines))


def report_installed():
    # 只说明 zip 是否已经生成过。选空间在后面的列举里。
    if not sys.stdin.isatty():
        if os.path.isfile(ENTERPRISE_ZIP):
            print("enterprise installed")
        return
    if os.path.isfile(ENTERPRISE_ZIP):
        print("Zip: already created", file=sys.stderr)


def write_enterprise_zip(target):
    with atomic_private_file(ENTERPRISE_ZIP, prefix=".enterprise-", suffix=".zip") as tmp:
        with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for dirpath, _dirnames, filenames in os.walk(target):
                for filename in filenames:
                    full = os.path.join(dirpath, filename)
                    rel = os.path.relpath(full, target).replace(os.sep, "/")
                    archive.write(full, rel)
    return ENTERPRISE_ZIP


def find_plugin_root(root):
    for dirpath, _dirnames, _filenames in os.walk(root):
        if os.path.basename(dirpath) != INSTALLER_NAME:
            continue
        if os.path.isfile(os.path.join(dirpath, ".qoder-plugin", "plugin.json")):
            return dirpath
    fail("Package does not contain %s" % INSTALLER_NAME)


def fetch_plugin(staging):
    archive = os.path.join(staging, "loongsuite-pilot-installer.zip")
    try:
        download_file(PLUGIN_ZIP_URL, archive)
    except Exception as exc:
        fail("Download failed: %s (%s)" % (PLUGIN_ZIP_URL, exc))
    unpacked = os.path.join(staging, "unpacked")
    os.makedirs(unpacked)
    with zipfile.ZipFile(archive) as handle:
        for item in handle.infolist():
            name = item.filename.replace("\\", "/")
            parts = name.split("/")
            drive_path = len(name) >= 3 and name[1] == ":" and name[2] == "/"
            if name.startswith("/") or drive_path or ".." in parts:
                fail("Package contains an unsafe path: %s" % item.filename)
            if stat.S_ISLNK(item.external_attr >> 16):
                fail("Package contains a symlink: %s" % item.filename)
        handle.extractall(unpacked)
    target = find_plugin_root(unpacked)
    os.makedirs(os.path.join(target, "config"), exist_ok=True)
    return target


def install_enterprise(target):
    zip_path = write_enterprise_zip(target)
    print("enterprise_zip=%s" % zip_path)


def get_install_fields(profile, agent_space, region):
    space = get_space(profile, agent_space, region)
    agent_space = space.get("agentSpace") or agent_space
    region = space.get("regionId") or region
    project = space.get("slsProject") or ""
    workspace = space.get("cmsWorkspace") or ""
    if not project or not workspace:
        fail("AgentSpace is missing slsProject or cmsWorkspace")
    access = get_observability(profile, region, workspace)
    token = access.get("authToken") or ""
    domain = access.get("publicDomain") or access.get("privateDomain") or ""
    if not token or not domain:
        fail("Service observability result is missing authToken or domain")
    if "://" in domain:
        endpoint = domain.rstrip("/") + "/apm/trace/opentelemetry"
    else:
        endpoint = "https://%s/apm/trace/opentelemetry" % domain.rstrip("/")
    key = get_api_key(profile, region, project)
    fields = [
        ("--collect-log", "true"),
        ("--collect-trace", "true"),
        ("--sls-project", project),
        ("--sls-logstore", DEFAULT_LOGSTORE),
        ("--sls-endpoint", "%s.log.aliyuncs.com" % region),
        ("--cms-license-key", token),
        ("--cms-endpoint", endpoint),
        ("--cms-workspace", workspace),
        ("--service-name-prefix", "ai-coding-agent"),
        ("--sls-api-key", key),
    ]
    return fields, project, agent_space, region


def run(argv):
    agent_space, region, user_id_source = parse_args(argv)
    profile = require_profile()
    if not agent_space:
        report_installed()
    fields, project, agent_space, region = get_install_fields(profile, agent_space, region)
    fields.append(("--install-source", INSTALL_SOURCE))
    os.makedirs(DATA_DIR, exist_ok=True)
    staging = tempfile.mkdtemp(prefix=".plugin-stage-", dir=DATA_DIR)
    try:
        target = fetch_plugin(staging)
        write_conf(os.path.join(target, "config", "install-params.conf"), fields, user_id_source)
        install_enterprise(target)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    save_target(agent_space, region, project, DEFAULT_LOGSTORE)


if __name__ == "__main__":
    run(sys.argv[1:])
