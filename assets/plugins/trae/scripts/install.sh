#!/usr/bin/env bash
# Loongsuite Pilot — Trae plugin-probe install script.
#
# Invoked by PluginProbeStrategy.deploy() (src/deployment/plugin-probe-strategy.ts:127-138)
# after the plugin bundle has been staged into $PILOT_DATA/plugins/trae/.
#
# Mount strategy: env-inject via NODE_OPTIONS preload. We write a PATH
# wrapper that intercepts `trae` / `trae-cn` invocations and exports
#   NODE_OPTIONS="--import file://<abs>/probe.mjs"
#   PILOT_LOG_DIR=<pilot data>/logs/trae
# before exec'ing the real Trae binary. PATH precedence takes care of the
# rest — the wrapper shadows any system `trae-cn` while Pilot is active.
#
# No worker.manifest.json is created. Trae itself is the "worker"; a
# manifest would make PluginProbeStrategy.needsDeploy() (plugin-probe-strategy.ts:59-63)
# try to start a separate worker daemon, which is wrong for this agent.

set -euo pipefail

AGENT_ID="trae"
PILOT_DATA_DIR="${PILOT_DATA_DIR:-$HOME/.loongsuite-pilot}"
PROBE_DIR="$PILOT_DATA_DIR/plugins/$AGENT_ID"
PROBE_FILE="$PROBE_DIR/probe.mjs"
WRAPPER_DIR="$PILOT_DATA_DIR/bin"
TRAE_COMMANDS=(trae trae-cn)

mkdir -p "$WRAPPER_DIR"

# Resolve the real Trae binary once, on install. We prefer an explicit
# TRAE_BIN env override, then PATH lookup, then common install locations.
resolve_real_trae() {
  if [[ -n "${TRAE_BIN:-}" && -x "${TRAE_BIN}" ]]; then
    echo "$TRAE_BIN"
    return
  fi
  local cmd
  for cmd in "${TRAE_COMMANDS[@]}"; do
    local p
    # Strip our wrapper dir from PATH so we don't recursively pick ourselves.
    local cleaned_path
    cleaned_path="$(echo "$PATH" | tr ':' '\n' | grep -v "^${WRAPPER_DIR}\$" | paste -sd:)"
    p="$(PATH="$cleaned_path" command -v "$cmd" 2>/dev/null || true)"
    if [[ -n "$p" && -x "$p" && "$p" != "$WRAPPER_DIR/$cmd" ]]; then
      echo "$p"
      return
    fi
  done
  for cand in \
    "$HOME/trae-install/trae-cn" \
    "$HOME/trae-install/trae" \
    /opt/Trae/bin/trae-cn \
    /opt/Trae/trae-cn \
    /usr/share/trae/trae-cn \
    /usr/local/bin/trae-cn \
    /Applications/Trae.app/Contents/MacOS/Trae; do
    if [[ -x "$cand" ]]; then
      echo "$cand"
      return
    fi
  done
  return 1
}

REAL_TRAE_BIN="$(resolve_real_trae || true)"
if [[ -z "$REAL_TRAE_BIN" ]]; then
  echo "[trae-plugin-probe] WARN: real trae binary not found on PATH; wrappers will fall through to command lookup at runtime." >&2
fi

# Persist the resolved binary path so the wrapper can fall back to it
# without re-running the discovery logic on every invocation.
STATE_FILE="$PROBE_DIR/.install-state"
cat > "$STATE_FILE" <<EOF
PILOT_DATA_DIR=$PILOT_DATA_DIR
PROBE_FILE=$PROBE_FILE
REAL_TRAE_BIN=$REAL_TRAE_BIN
INSTALLED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF

LOG_DIR="$PILOT_DATA_DIR/logs/$AGENT_ID"
mkdir -p "$LOG_DIR"

# Write one wrapper per Trae command name. Each wrapper is a thin shell
# script that exports the NODE_OPTIONS preload + PILOT_LOG_DIR then execs
# the real binary. Appended args pass through.
write_wrapper() {
  local cmd="$1"
  local wrapper="$WRAPPER_DIR/$cmd"
  cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Auto-generated by loongsuite-pilot trae plugin-probe install.sh.
# Do not edit — re-run \`loongsuite-pilot deploy trae\` to regenerate.
PILOT_DATA_DIR="\${PILOT_DATA_DIR:-$HOME/.loongsuite-pilot}"
export PILOT_LOG_DIR="\${PILOT_LOG_DIR:-\$PILOT_DATA_DIR/logs/$AGENT_ID}"
PROBE_FILE="\${PILOT_TRAE_PROBE:-$PROBE_FILE}"
if [[ ! -f "\$PROBE_FILE" ]]; then
  echo "[trae-plugin-probe] WARN: probe.mjs missing at \$PROBE_FILE; starting Trae without instrumentation." >&2
else
  if [[ -n "\${NODE_OPTIONS:-}" ]]; then
    case " \$NODE_OPTIONS " in
      *" --import file://\$PROBE_FILE "*|*" --import "\$PROBE_FILE" "*)
        ;;
      *)
        export NODE_OPTIONS="\$NODE_OPTIONS --import file://\$PROBE_FILE"
        ;;
    esac
  else
    export NODE_OPTIONS="--import file://\$PROBE_FILE"
  fi
fi
REAL_BIN="\${TRAE_BIN:-$REAL_TRAE_BIN}"
if [[ -z "\$REAL_BIN" || ! -x "\$REAL_BIN" ]]; then
  # Fall back to PATH lookup with our wrapper dir stripped so we don't recurse.
  cleaned_path="\$(echo "\$PATH" | tr ':' '\n' | grep -v "^\$(dirname "\$0")\$" | paste -sd:)"
  REAL_BIN="\$(PATH="\$cleaned_path" command -v "$cmd" 2>/dev/null || true)"
fi
if [[ -z "\$REAL_BIN" ]]; then
  echo "[trae-plugin-probe] ERROR: $cmd not found on PATH." >&2
  exit 127
fi
exec "\$REAL_BIN" "\$@"
EOF
  chmod +x "$wrapper"
}

for cmd in "${TRAE_COMMANDS[@]}"; do
  write_wrapper "$cmd"
done

# Prepend the wrapper dir to the user's shell rc so future shells find our
# wrapper first. We only edit rc files when rc-inject is NOT already in
# effect (PluginProbeStrategy uses mountType=env-inject, so rc edits are
# our responsibility — but we guard against double-injection).
inject_rc_path() {
  local rc="$1"
  [[ -f "$rc" ]] || return 0
  if grep -q "# loongsuite-pilot trae plugin-probe PATH" "$rc"; then
    return 0
  fi
  cat >> "$rc" <<EOF

# loongsuite-pilot trae plugin-probe PATH
case ":\$PATH:" in
  *":$WRAPPER_DIR:"*) ;;
  *) export PATH="$WRAPPER_DIR:\$PATH" ;;
esac
EOF
}

inject_rc_path "$HOME/.bashrc"
inject_rc_path "$HOME/.zshrc"
inject_rc_path "$HOME/.profile"

# Intentionally do NOT create $PROBE_DIR/worker.manifest.json. Trae is the
# worker; a manifest would make PluginProbeStrategy spin up a daemon.

echo "[trae-plugin-probe] installed. Wrappers at $WRAPPER_DIR/{trae,trae-cn}."
echo "[trae-plugin-probe] probe at $PROBE_FILE; log dir $LOG_DIR."
if [[ -n "$REAL_TRAE_BIN" ]]; then
  echo "[trae-plugin-probe] resolved real trae binary: $REAL_TRAE_BIN"
fi
echo "[trae-plugin-probe] open a new shell (or source ~/.bashrc) to pick up PATH."

exit 0
