use super::*;
use serde_json::json;
fn user(text: Value) -> Value {
    json!({"type":"user","userType":"external","entrypoint":"cli","timestamp":"2026-08-27T06:50:52.808Z","message":{"role":"user","content":text}})
}
fn prompt(text: &str) -> Value {
    let mut row = user(json!(text));
    row["promptId"] = json!("21c3d055-6800-48b0-a892-c40386abc77c");
    row["timestamp"] = json!("2026-08-27T06:50:56.000Z");
    row
}
fn assistant(timestamp: &str, message: Value) -> Value {
    let mut message = message;
    message["role"] = json!("assistant");
    json!({"type":"assistant","timestamp":timestamp,"message":message})
}
fn answer() -> Value {
    assistant(
        "2026-08-27T06:50:57.000Z",
        json!({"model":"auto","stop_reason":"end_turn","content":[{"type":"text","text":"杭州今天多云。"}]}),
    )
}
fn caveat() -> Value {
    let mut r=user(json!("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"));
    r["isMeta"] = json!(true);
    r
}
fn command() -> Value {
    user(json!(
        "<command-message>model</command-message>\n<command-name>/model</command-name>"
    ))
}
fn stdout() -> Value {
    let mut r = user(json!(
        "<local-command-stdout>Model set to Ultimate (persisted)</local-command-stdout>"
    ));
    r["isMeta"] = json!(true);
    r
}
fn result(id: &str) -> Value {
    let mut r = user(json!([{"type":"tool_result","tool_use_id":id,"content":"ok"}]));
    r["timestamp"] = json!("2026-08-27T06:50:58.000Z");
    r["toolUseResult"] = json!("ok");
    r
}
fn build(rows: &[Value], agent: &str) -> Vec<Value> {
    let stamp = Stamp {
        span: Obj::new(),
        resources: Obj::new(),
        agent_name: None,
    };
    build_events_from_boundaries(
        &build_llm_boundaries(rows),
        rows,
        rows,
        "turn-1",
        BoundaryContext {
            session_id: "session-1",
            agent_id: agent,
            runtime_user: "u",
            identity: None,
            cwd: Some("/tmp/cwd"),
            stamp: &stamp,
        },
    )
    .into_iter()
    .map(Value::Object)
    .collect()
}
fn named<'a>(rows: &'a [Value], event: &str) -> Vec<&'a Value> {
    rows.iter().filter(|r| r["event.name"] == event).collect()
}
fn parts(record: &Value) -> Vec<String> {
    record["gen_ai.input.messages_delta"][0]["parts"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|p| p["content"].as_str().unwrap_or("").to_owned())
        .collect()
}
fn response(id: &str, usage: Option<Value>) -> Value {
    let mut msg = json!({"id":id,"model":"qwen-max","content":[{"type":"text","text":"done"}],"stop_reason":"end_turn"});
    if let Some(usage) = usage {
        msg["usage"] = usage;
    }
    assistant("2026-08-03T09:22:26.000000Z", msg)
}
fn user_plain() -> Value {
    json!({"type":"user","timestamp":"2026-08-03T09:22:25.100000Z","message":{"role":"user","content":"explain spans"}})
}
#[test]
fn client_l38_closing_stream_usage_preserves_client_request_id_separate_from_provider_id() {
    let rows = [
        user_plain(),
        assistant(
            "2026-08-03T09:22:26.000000Z",
            json!({"id":"resp_074f8158b56ee638016a968589ddb48193","model":"qwen-max","content":[{"type":"text","content":"partial","text":"partial"}]}),
        ),
        assistant(
            "2026-08-03T09:22:27.000000Z",
            json!({"model":"qwen-max","content":[{"type":"text","text":"done"}],"stop_reason":"end_turn","usage":{"input_tokens":29194,"output_tokens":43,"request_id":"f2a2d7da-9bd0-4dd8-b144-195adc8ffc32"}}),
        ),
    ];
    let records = build(&rows, "qoder");
    let r = named(&records, "llm.response")[0];
    assert_eq!(
        r["agent.client_request_id"],
        "f2a2d7da-9bd0-4dd8-b144-195adc8ffc32"
    );
    assert_eq!(
        r["gen_ai.response.id"],
        "resp_074f8158b56ee638016a968589ddb48193"
    );
}
