#[test]
fn client_l114_each_tool_step_keeps_its_own_cli_request_id() {
    let rows = [
        user_plain(),
        assistant(
            "2026-08-03T09:22:25.555446Z",
            json!({"id":"resp_step_one","model":"qwen-max","content":[{"type":"tool_use","id":"tool-b","name":"Read","input":{}}],"stop_reason":"tool_use","usage":{"request_id":"cli-req-step-1"}}),
        ),
        json!({"type":"user","timestamp":"2026-08-03T09:22:26.668419Z","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"tool-b","content":"ok"}]}}),
        assistant(
            "2026-08-03T09:22:26.999890Z",
            json!({"id":"resp_step_two","model":"qwen-max","content":[{"type":"text","text":"done"}],"stop_reason":"end_turn","usage":{"request_id":"cli-req-step-2"}}),
        ),
    ];
    let records = build(&rows, "qoder");
    assert_eq!(
        named(&records, "llm.response")
            .iter()
            .map(|r| r["agent.client_request_id"].as_str().unwrap())
            .collect::<Vec<_>>(),
        ["cli-req-step-1", "cli-req-step-2"]
    );
}
#[test]
fn client_l157_client_id_survives_actual_log_projection_while_scoped_match_timestamp_is_removed() {
    let records = build(
        &[
            user_plain(),
            response("message-1", Some(json!({"request_id":"cli-req-A"}))),
        ],
        "qoder",
    );
    let r = named(&records, "llm.response")[0];
    assert!(r["agent.qoder.match_ts"].is_number());
    let typed: crate::types::AgentActivityEntry = serde_json::from_value(r.clone()).unwrap();
    let projected = crate::normalization::project_log_entry(
        &typed,
        &crate::normalization::SerialiseLogEntryOptions {
            drop_agent_scoped_fields: true,
        },
    );
    assert_eq!(projected["agent.client_request_id"], "cli-req-A");
    assert!(projected.get("agent.qoder.match_ts").is_none());
}
