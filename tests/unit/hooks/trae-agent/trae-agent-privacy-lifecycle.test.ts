// Generated by bytedance/trae-agent's TrajectoryRecorder at e839e559 using
// synthetic tasks and a simulated failure before a provider response.
const failedFixture = path.resolve(__dirname, 'fixtures/fixture_trajectory_failed_before_response.json');
const converterPath = path.resolve(__dirname, '../../../../assets/hooks/trae-agent/trajectory-converter.mjs');
let temporary: string;

beforeEach(async () => {
  temporary = await mkdtemp(path.join(tmpdir(), 'pilot-trae-lifecycle-'));
});

