test.each(['source', 'workspace', 'legacy', 'mixed', 'allowed', 'legacy-without-exclusions'])(
  'rechecks Trae provenance after a durable journal restart (%s)', async scenario => {
    const project = path.join(temporary, 'project');
    const central = path.join(temporary, 'central');
    await mkdir(project);
    await mkdir(central);
    const trajectory = path.join(central, 'trajectory.json');
    await writeFile(trajectory, await readFile(failedFixture));
    const sourcePath = await realpath(trajectory);
    const { input } = await newInput(trajectory, project);
    const records = await collectAndQueue(input);
    expect(records).toHaveLength(2);
    expect(records.every(record => record['agent.trajectory.source.path'] === sourcePath)).toBe(true);

    const journalDir = path.join(temporary, 'pending');
    const journal = () => new CodexTurnJournal(journalDir, 100, ['codex', 'hermes', 'openclaw', 'trae-agent']);
    await journal().append(records.map((record, index) =>
      scenario === 'legacy' || scenario === 'legacy-without-exclusions' || (scenario === 'mixed' && index === 1)
        ? { ...record, 'agent.trajectory.source.path': undefined } : record));
    await unlink(trajectory);

    const exclusion = scenario === 'source' ? central : scenario === 'workspace' ? project : path.join(temporary, 'other');
    const manager = new InputManager();
    manager.setWorkspacePolicy(new WorkspacePolicy(scenario === 'legacy-without-exclusions' ? [] : [exclusion]));
    const spans: ReadableSpan[] = [];
    const flusher = new OtlpTraceFlusher({ enabled: true, serviceName: 'trae-replay-test',
      protocol: 'http/protobuf', endpoints: [{ endpoint: 'http://localhost:4318/v1/traces', headers: {} }],
      resourceAttributeKeys: ['agent.trajectory.source.path'],
      spanAttributePassthroughPrefixes: ['agent.trajectory.'],
    }, undefined, () => ({
      export(batch, done) { spans.push(...batch); done({ code: 0 }); },
      shutdown: async () => {},
    }), journal(), batch => manager.prepareRestoredEntries(batch));
    try {
      await flusher.start();
      await flusher.flush();
    } finally {
      await flusher.shutdown();
    }
    const expected = scenario === 'allowed' || scenario === 'legacy-without-exclusions' ? ['AGENT', 'ENTRY'] : [];
    expect(spans.map(span => span.attributes['gen_ai.span.kind']).sort()).toEqual(expected);
    for (const span of spans) {
      expect(span.attributes).not.toHaveProperty(['agent.trajectory.source.path']);
      expect(span.resource.attributes).not.toHaveProperty(['agent.trajectory.source.path']);
    }
    expect((await readdir(journalDir)).some(name => name.startsWith('codex-turn-') && name.endsWith('.jsonl'))).toBe(false);
  },
);

test('exports a finalized pre-response failure once without synthesizing model or tool spans', async () => {
  const trajectoryFile = path.join(temporary, 'trajectory.json');
  const raw = JSON.parse(await readFile(failedFixture, 'utf8'));
  const { input, stateStore } = await newInput(trajectoryFile);
  const manager = new InputManager();
  const spans: ReadableSpan[] = [];
  const flusher = new OtlpTraceFlusher({
    enabled: true,
    serviceName: 'trae-failure-test',
    captureMessageContent: false,
    protocol: 'http/protobuf',
    endpoints: [{ endpoint: 'http://localhost:4318/v1/traces', headers: {} }],
  }, undefined, () => ({
    export(batch, done) { spans.push(...batch); done({ code: 0 }); },
    shutdown: async () => {},
  }));
  manager.setFlusher(flusher);
  manager.registerInput(input);
  try {
    await flusher.start();
    await writeFile(trajectoryFile, JSON.stringify({ ...raw, end_time: '' }));
    await manager.startInput(input.id);
    await manager.stopInput(input.id);
    expect(spans).toEqual([]);

    // Interactive recording can carry the preceding turn's end time until
    // finalization, even when both times round to the same millisecond.
    const earlierEnd = raw.start_time.replace(/\d{3}$/, '000');
    await writeFile(trajectoryFile, JSON.stringify({ ...raw, end_time: earlierEnd }));
    await manager.startInput(input.id);
    await manager.stopInput(input.id);
    expect(stateStore.get(input.id).extra?.runCompletionEmitted).toBe(false);

    await writeFile(trajectoryFile, JSON.stringify(raw));
    await manager.startInput(input.id);
    await manager.stopInput(input.id);
    await flusher.flush();
    expect(spans.map(span => span.attributes['gen_ai.span.kind']).sort()).toEqual(['AGENT', 'ENTRY']);
    expect(spans.every(span => span.status.code === 2
      && span.attributes['error.type'] === 'trae_agent.run_failed_before_response')).toBe(true);
    expect(spans.every(span => span.duration[0] === 0 && span.duration[1] === 214_000)).toBe(true);
    const entry = spans.find(span => span.attributes['gen_ai.span.kind'] === 'ENTRY')!;
    const agent = spans.find(span => span.attributes['gen_ai.span.kind'] === 'AGENT')!;
    expect(entry.parentSpanId).toBeUndefined();
    expect(agent.parentSpanId).toBe(entry.spanContext().spanId);
    expect(JSON.stringify(spans.map(span => span.attributes))).not.toContain(raw.final_result);

    await stateStore.save();
    const { input: restarted } = await newInput(trajectoryFile);
    expect(await collectAndQueue(restarted)).toEqual([]);
  } finally {
    await manager.stopAll();
    await flusher.shutdown();
  }
});

test('keeps the canonical trajectory source out of HTTP and JSONL event output', async () => {
  const project = path.join(temporary, 'project');
  const external = path.join(temporary, 'collection-inputs');
  const outputDir = path.join(temporary, 'output');
  await mkdir(project);
  await mkdir(external);
  const trajectory = path.join(external, 'private-source-name.json');
  await writeFile(trajectory, await readFile(failedFixture));
  const source = await realpath(trajectory);
  const { input } = await newInput(trajectory, project);
  const received: string[] = [];
  const server = createServer((request, response) => {
    request.setEncoding('utf8');
    let body = '';
    request.on('data', chunk => { body += chunk; });
    request.on('end', () => {
      received.push(body);
      response.writeHead(200).end();
    });
  });
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });

  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('HTTP test listener has no port');
  const http = new HttpFlusher({
    enabled: true, url: `http://127.0.0.1:${address.port}`, batchMaxSize: 1,
    flushIntervalMs: 60_000, requestTimeoutMs: 1_000,
  });
  const jsonl = new JsonlFlusher({ enabled: true, outputDir, rotateDaily: false, maxFileSizeMb: 10 });
  const manager = new InputManager();
  manager.setAgentsConfig({ 'trae-agent': { captureMessageContent: false } });
  manager.setWorkspacePolicy(new WorkspacePolicy([path.join(temporary, 'excluded')]));
  manager.setFlusher(new MultiFlusher([http, jsonl]));
  manager.registerInput(input);
  try {
    await jsonl.start();
    await http.start();
    await manager.startInput(input.id);
    await manager.stopInput(input.id);
    const httpRows = received.flatMap(body => JSON.parse(body).entries);
    expect(httpRows).toHaveLength(2);
    const lines = (await readFile(path.join(outputDir, 'trae-agent-all.jsonl'), 'utf8')).trim().split('\n');
    expect(lines).toHaveLength(2);
    for (const row of [...httpRows, ...lines.map(line => JSON.parse(line))]) {
      expect(row['workspace.path']).toBe(project);
    }
    for (const payload of [...received, ...lines]) {
      expect(payload).not.toContain('agent.trajectory.source.path');
      expect(payload).not.toContain(JSON.stringify(source));
    }
  } finally {
    await manager.stopAll();
    await http.shutdown();
    await jsonl.shutdown();
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  }
});
